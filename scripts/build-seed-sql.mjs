// Build supabase/seed-curriculum.sql from src/lib/curriculum.ts (single source of truth).
// Run: node scripts/build-seed-sql.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
let src = fs.readFileSync(path.join(root, "src/lib/curriculum.ts"), "utf8");
// Strip the TS-only header up to the first `export const LEVELS`
src = src.slice(src.indexOf("export const LEVELS"));
src = src.replace(/export const /g, "const ").replace(/ as const;/g, ";");
src = src.replace("const TOPICS: Topic[] =", "const TOPICS =");
src = src.replace(/const CERTIFICATE_TITLES: Record<number, string> =/, "const CERTIFICATE_TITLES =");
// Remove helper functions at the end
src = src.slice(0, src.indexOf("export function"));
const fn = new Function(`${src}\nreturn { LEVELS, TOPICS, EXAMS };`);
const { LEVELS, TOPICS, EXAMS } = fn();
const q = (s) => "'" + String(s ?? "").replace(/'/g, "''") + "'";
const lines = [];
lines.push("-- Nexora Web Dev. Academy — curriculum seed (generated by scripts/build-seed-sql.mjs).");
lines.push("-- Source of truth: scripts/generate-curriculum.mjs -> src/lib/curriculum.ts.");
lines.push("-- Rerunnable: all inserts use ON CONFLICT DO NOTHING. Apply AFTER 001_schema.sql.");
lines.push("-- Counts: 73 topics, 730 quiz questions, 3 examinations.");
lines.push("");
lines.push("insert into public.courses (slug, title, description) values ('web-dev-academy','Nexora Web Dev. Academy','Beginner, Intermediate and Advanced web development.') on conflict (slug) do nothing;");
lines.push("");
const modules = [...new Set(TOPICS.map((t) => `${t.level}|${t.module}`))];
for (const m of modules) {
  const [level, title] = m.split("|");
  lines.push(`insert into public.modules (level_id, title, position) values (${level}, ${q(title)}, 0) on conflict (level_id, title) do nothing;`);
}
lines.push("");
for (const t of TOPICS) {
  lines.push(`insert into public.topics (module_id, slug, title, summary, position, published) select id, ${q(t.slug)}, ${q(t.title)}, ${q(t.summary)}, 0, true from public.modules where level_id = ${t.level} and title = ${q(t.module)} on conflict (slug) do nothing;`);
  lines.push(`insert into public.lessons (topic_id, objectives, explanation, code_lang, code, code_explanation, activity, mistakes, recap, version) select id, ${q(JSON.stringify(t.objectives))}::jsonb, ${q(JSON.stringify(t.explanation))}::jsonb, ${q(t.codeLang)}, ${q(t.code)}, ${q(t.codeExplanation)}, ${q(t.activity)}, ${q(JSON.stringify(t.mistakes))}::jsonb, ${q(t.recap)}, 1 from public.topics where slug = ${q(t.slug)} on conflict (topic_id, version) do nothing;`);
  lines.push(`insert into public.quizzes (topic_id, pass_mark) select id, 7 from public.topics where slug = ${q(t.slug)} on conflict (topic_id) do nothing;`);
  // One DO block per topic: insert each question, capture its id, then
  // insert exactly its 4 options. Avoids matching by question text (some
  // template questions repeat across topics).
  lines.push(`do $$ declare qid uuid; qzid uuid; begin`);
  lines.push(`  select id into qzid from public.quizzes where topic_id = (select id from public.topics where slug = ${q(t.slug)});`);
  lines.push(`  if qzid is null then return; end if;`);
  lines.push(`  if (select count(*) from public.quiz_questions where quiz_id = qzid) > 0 then return; end if; -- already seeded`);
  t.questions.forEach((qq, qi) => {
    lines.push(`  insert into public.quiz_questions (quiz_id, question_text, explanation, position, version) values (qzid, ${q(qq.q)}, ${q(qq.explanation)}, ${qi}, 1) returning id into qid;`);
    qq.options.forEach((opt, oi) => {
      lines.push(`  insert into public.quiz_options (question_id, option_text, is_correct, position) values (qid, ${q(opt)}, ${oi === qq.answer}, ${oi});`);
    });
  });
  lines.push(`end $$;`);
}
lines.push("");
for (const e of EXAMS) {
  lines.push(`insert into public.examinations (level_id, title, duration_minutes, pass_mark_percent, instructions, rubric) values (${e.level}, ${q(e.title)}, ${e.durationMinutes}, ${e.passMarkPercent}, ${q(e.instructions)}, ${q(e.rubric)}) on conflict (level_id) do nothing;`);
}
lines.push("");
lines.push("-- Verification: select count(*) from public.topics; -- 73");
lines.push("-- select count(*) from public.quiz_questions; -- 730");
lines.push("-- select count(*) from public.examinations; -- 3");
fs.writeFileSync(path.join(root, "supabase/seed-curriculum.sql"), lines.join("\n") + "\n");
console.log(`seed written: ${TOPICS.length} topics, ${TOPICS.reduce((n, t) => n + t.questions.length, 0)} questions, ${EXAMS.length} exams`);
